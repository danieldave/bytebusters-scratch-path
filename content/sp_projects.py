def P(id,kind,title,emoji,level,themes,hook,problem,learn,steps,missions,ask,remix,showcase=False,school=None,link=None,mins=None):
    d=dict(id=id,kind=kind,title=title,emoji=emoji,level=level,themes=themes,hook=hook,problem=problem,learn=learn,
      steps=[{'t':a,'b':b} for a,b in steps],
      missions=[({'t':m[0],'rule':m[1]} if isinstance(m,tuple) else {'t':m}) for m in missions],
      ask=ask,remix=remix,showcase=showcase)
    if school:d['school']=school
    if link:d['link']=link
    if mins:d['mins']=mins
    return d
R=lambda p,n=1:{'p':p,'min':n}
C=lambda c,n:{'count':c,'min':n}

